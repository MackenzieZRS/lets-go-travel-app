// Fallback lookup function with fuzzy matching
export function getDestinationImage(destinationName: string): { url: string; alt: string; photographer: string } {
  const key = destinationName.toLowerCase().trim();
  
  // Direct match
  if (DESTINATION_IMAGES[key]) return DESTINATION_IMAGES[key];
  
  // Partial match — find first key that includes the destination name
  const partialMatch = Object.keys(DESTINATION_IMAGES).find(
    k => k.includes(key) || key.includes(k)
  );
  if (partialMatch) return DESTINATION_IMAGES[partialMatch];
  
  // GUARANTEED fallback — never returns undefined, never shows blank card
  return {
    url: "https://images.unsplash.com/photo-1469854523086-cc02fe5d8800?w=800&q=80",
    alt: `${destinationName} travel destination`,
    photographer: "Unsplash"
  };
}
